export const generateHistoricalData = () => {
  const data = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 60 * 60000);
    data.push({
      time: time.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' }),
      rainfall: 45 + Math.random() * 50,
      waterLevel: 35 + Math.random() * 50,
      soilMoisture: 55 + Math.random() * 40,
      riskScore: 40 + Math.random() * 50,
    });
  }
  return data;
};
